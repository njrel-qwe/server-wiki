/* ============================================================
   Слияние с автогенерацией: js/items-gen.js подключается РАНЬШЕ этого файла.
   Имя, лор, редкость, сила, ветка, заряды, откат и материал берутся из конфига
   плагина, чтобы сайт не расходился с игрой.
   ============================================================ */
(function () {
  var G = window.GEN;
  if (!G) return;
  function strip(s) { return (s || '').replace(/&[0-9a-fk-or]/gi, '').replace(/[❖]/g, '').trim(); }
  window.ITEMS.forEach(function (it) {
    var g = G.items[it.id];
    if (!g) return;
    it.name = strip(g.name);
    it.lore = [g.name].concat(g.lore || []);
    ['rarity', 'power', 'branch', 'uses', 'cd', 'material'].forEach(function (k) {
      if (g[k] != null) it[k] = g[k];
    });
  });
})();
